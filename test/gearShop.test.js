import assert from 'node:assert/strict';
import { memoryStore } from './teamProcesses.test.js';
import { equipGearItem, purchaseGearItem, rewardGearContribution } from '../src/services/gearShop.js';
import { DAILY_GEARS_LIMIT, gearDay, gearItem, GEAR_SHOP_ITEMS, newGearProfile } from '../src/utils/gearShop.js';

export async function runGearShopTests() {
  assert.equal(new Set(GEAR_SHOP_ITEMS.map((item) => item.id)).size, GEAR_SHOP_ITEMS.length);
  assert.ok(GEAR_SHOP_ITEMS.every((item) => Number.isSafeInteger(item.price) && item.price >= 0));
  assert.equal(gearDay(new Date('2026-10-28T01:30:00Z')), '2026-10-27', 'Daily rewards follow São Paulo, not the server date');
  const source = { createdByStudentId: 'a', title: 'Saída com sensor' };
  const memory = memoryStore({ 'students/a': { name: 'Ana', status: 'active', xp: 125 }, 'students/b': { name: 'Bruno', status: 'active', xp: 100 }, 'codeSnippets/c1': source, 'codeSnippets/c2': source, 'codeSnippets/c3': source, 'codeSnippets/foreign': { ...source, createdByStudentId: 'b' }, 'experts/e1': { name: 'Especialista', createdByStudentId: 'a' }, 'experts/e2': { name: 'Pesquisador', createdByStudentId: 'a' }, 'experts/e3': { name: 'Mentor', createdByStudentId: 'a' } });
  const context = { db: {}, user: { type: 'student', data: { id: 'a' } }, studentId: 'a', store: memory.store };
  const now = new Date('2026-10-27T15:00:00Z');
  const earned = await rewardGearContribution({ ...context, type: 'code', sourceId: 'c1', referenceDate: now });
  assert.equal(earned.coins, 12);
  assert.equal(memory.records.get('studentGearProfiles/a').balance, 52, 'Welcome Gears are credited exactly once');
  assert.equal((await rewardGearContribution({ ...context, type: 'code', sourceId: 'c1', referenceDate: now })).duplicate, true);
  assert.equal(memory.records.get('studentGearProfiles/a').balance, 52);
  await assert.rejects(rewardGearContribution({ ...context, type: 'code', sourceId: 'foreign' }), /seu nome/);
  await assert.rejects(rewardGearContribution({ ...context, type: 'code', sourceId: 'missing' }), /seu nome/);
  await assert.rejects(rewardGearContribution({ ...context, type: 'code', sourceId: 'bad/path' }), /inválida/);
  await rewardGearContribution({ ...context, type: 'code', sourceId: 'c2', referenceDate: now });
  assert.equal((await rewardGearContribution({ ...context, type: 'code', sourceId: 'c3', referenceDate: now })).coins, 0, 'Repeated registrations respect the category daily limit');
  await rewardGearContribution({ ...context, type: 'expert', sourceId: 'e1', referenceDate: now });
  await rewardGearContribution({ ...context, type: 'expert', sourceId: 'e2', referenceDate: now });
  assert.equal(memory.records.get('studentGearProfiles/a').dayEarned, DAILY_GEARS_LIMIT, 'The last reward is capped at the remaining daily amount');
  assert.equal((await rewardGearContribution({ ...context, type: 'expert', sourceId: 'e3', referenceDate: now })).coins, 0);
  const beforePurchase = structuredClone(memory.records.get('studentGearProfiles/a'));
  const bought = await purchaseGearItem({ ...context, itemId: 'skin-solar' });
  assert.equal(bought.balance, beforePurchase.balance - gearItem('skin-solar').price);
  assert.equal(bought.equipped.skin, 'skin-solar');
  assert.equal(memory.records.get('students/a').gearAppearance.skin, 'skin-solar');
  assert.equal(memory.records.get('students/a').xp, 125, 'Cosmetics never spend or award XP');
  await assert.rejects(purchaseGearItem({ ...context, itemId: 'skin-solar' }), /já tem/);
  await assert.rejects(equipGearItem({ ...context, itemId: 'accessory-crown' }), /Desbloqueie/);
  await equipGearItem({ ...context, itemId: 'skin-nebula' });
  assert.equal(memory.records.get('students/a').gearAppearance.skin, 'skin-nebula');
  assert.equal(memory.records.get('studentGearProfiles/a').balance, bought.balance, 'Equipping owned items is free');
  await assert.rejects(purchaseGearItem({ ...context, itemId: 'not-in-catalog' }), /catálogo/);
  await assert.rejects(purchaseGearItem({ ...context, studentId: 'b', itemId: 'skin-solar' }), /seu perfil/);
  await assert.rejects(purchaseGearItem({ ...context, user: { type: 'admin', studentId: 'a' }, itemId: 'skin-solar' }), /seu perfil/);
  memory.records.get('studentGearProfiles/a').balance = 0;
  memory.records.get('studentGearProfiles/a').earned = memory.records.get('studentGearProfiles/a').spent;
  await assert.rejects(purchaseGearItem({ ...context, itemId: 'accessory-crown' }), /suficientes/);
  memory.records.get('studentGearProfiles/a').balance = 100;
  memory.records.get('studentGearProfiles/a').earned = memory.records.get('studentGearProfiles/a').spent + 100;
  const beforeFailure = structuredClone([...memory.records]);
  const interrupted = { ...memory.store, runTransaction: (_db, action) => memory.store.runTransaction(_db, async (transaction) => { await action(transaction); throw new Error('Connection interrupted'); }) };
  await assert.rejects(purchaseGearItem({ ...context, store: interrupted, itemId: 'accessory-visor' }), /interrupted/);
  assert.deepEqual([...memory.records], beforeFailure, 'Failed purchases never charge coins or equip partial items');
  const tomorrow = new Date('2026-10-28T15:00:00Z');
  assert.equal((await rewardGearContribution({ ...context, type: 'code', sourceId: 'c3', referenceDate: tomorrow })).duplicate, true, 'Capped records cannot be replayed on another day');
  memory.records.set('codeSnippets/new-day', source);
  assert.equal((await rewardGearContribution({ ...context, type: 'code', sourceId: 'new-day', referenceDate: tomorrow })).coins, 12);
  memory.records.set('students/a/logbook/l1', { studentId: 'a', text: 'Hoje aprendemos a comparar os resultados dos testes.' });
  assert.equal((await rewardGearContribution({ ...context, type: 'logbook', sourceId: 'l1', referenceDate: tomorrow })).coins, 5, 'Logbook rewards use the student subcollection');
  const validAccount = structuredClone(memory.records.get('studentGearProfiles/a'));
  memory.records.get('studentGearProfiles/a').balance = '100';
  await assert.rejects(equipGearItem({ ...context, itemId: 'skin-nebula' }), /valores da carteira/);
  memory.records.set('studentGearProfiles/a', validAccount);
  memory.records.get('students/a').status = 'inactive';
  await assert.rejects(equipGearItem({ ...context, itemId: 'skin-nebula' }), /ativo/);
}
